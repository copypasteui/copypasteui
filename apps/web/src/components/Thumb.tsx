"use client";

import { useEffect, useRef, useState } from "react";

// thumbs/previews.json (from scripts/previews.mjs): which cards have a preview video, and how many seconds in
// the page had painted. Fetched once per page; a missing file just means still images.
let manifest: Promise<Record<string, number>> | null = null;
const loadManifest = () =>
  (manifest ??= fetch("/thumbs/previews.json")
    .then((r): Promise<Record<string, number>> => (r.ok ? r.json() : Promise.resolve({})))
    .catch((): Record<string, number> => ({})));

const wantsStill = () =>
  window.matchMedia("(prefers-reduced-motion: reduce)").matches ||
  Boolean((navigator as Navigator & { connection?: { saveData?: boolean } }).connection?.saveData);

/** Muted loop over the thumbnail that plays while the card is on screen. */
function PreviewVideo({ src, start }: { src: string; start: number }) {
  const ref = useRef<HTMLVideoElement>(null);
  const [playing, setPlaying] = useState(false);

  useEffect(() => {
    const video = ref.current;
    if (!video) return;
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry?.isIntersecting) {
          if (!video.src) video.src = src;
          if (video.currentTime < start) video.currentTime = start;
          video.play().catch(() => {});
        } else {
          video.pause();
        }
      },
      { threshold: 0.6 },
    );
    io.observe(video);
    return () => io.disconnect();
  }, [src, start]);

  return (
    <video
      ref={ref}
      muted
      playsInline
      preload="none"
      aria-hidden
      tabIndex={-1}
      onPlaying={() => setPlaying(true)}
      onTimeUpdate={(e) => {
        if (e.currentTarget.currentTime < start) e.currentTarget.currentTime = start;
      }}
      onEnded={(e) => {
        e.currentTarget.currentTime = start;
        e.currentTarget.play().catch(() => {});
      }}
      onError={() => setPlaying(false)}
      className={`pointer-events-none absolute inset-0 size-full object-cover object-top transition duration-500 group-hover:scale-[1.03] ${playing ? "opacity-100" : "opacity-0"}`}
    />
  );
}

/**
 * Screenshot thumbnail generated by scripts/screenshots.mjs, with the preview video from scripts/previews.mjs
 * on top when there is one. If the image doesn't exist yet (e.g. `next dev` before screenshots were taken) it
 * falls back to a scaled live preview.
 */
export default function Thumb({
  src,
  previewSrc,
  alt,
  className = "",
}: {
  src: string;
  previewSrc: string;
  alt: string;
  className?: string;
}) {
  const [failed, setFailed] = useState(false);
  const [start, setStart] = useState<number | null>(null);
  const key = src.match(/^\/thumbs\/((?:templates|components)\/[^/]+)\.jpg$/)?.[1];

  useEffect(() => {
    if (!key || wantsStill()) return;
    let live = true;
    loadManifest().then((m) => live && typeof m[key] === "number" && setStart(m[key]));
    return () => {
      live = false;
    };
  }, [key]);

  if (failed) {
    return (
      <iframe
        src={previewSrc}
        title={alt}
        loading="lazy"
        sandbox="allow-scripts"
        tabIndex={-1}
        aria-hidden
        className="pointer-events-none absolute top-0 left-0 h-[400%] w-[400%] origin-top-left scale-25 border-0"
      />
    );
  }
  return (
    <>
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={src}
        alt={alt}
        loading="lazy"
        decoding="async"
        onError={() => setFailed(true)}
        className={`absolute inset-0 size-full object-cover object-top transition-transform duration-500 group-hover:scale-[1.03] ${className}`}
      />
      {key && start !== null && <PreviewVideo src={src.replace(/\.jpg$/, ".webm")} start={start} />}
    </>
  );
}
